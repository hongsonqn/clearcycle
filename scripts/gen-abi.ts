/**
 * Regenerates src/lib/abi.ts from the Foundry artifact so the UI, API and indexer
 * share one ABI. Run `forge build` first, then `bun run abi:gen`.
 */
import { readFileSync, writeFileSync } from 'node:fs'

const artifact = JSON.parse(
  readFileSync('contracts/out/ClearingHouse.sol/ClearingHouse.json', 'utf8'),
) as { abi: unknown[] }

const body = `// Generated by scripts/gen-abi.ts from the ClearingHouse Foundry artifact. Do not edit.
export const clearingHouseAbi = ${JSON.stringify(artifact.abi, null, 2)} as const
`
writeFileSync('src/lib/abi.ts', body)
console.log(`wrote src/lib/abi.ts (${artifact.abi.length} entries)`)
